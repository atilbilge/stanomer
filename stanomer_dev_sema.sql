      updated_at       = now()
    WHERE id = p_contract_id;
  ELSE
    -- ANY PARTY proposing a revision to be accepted by the other
    UPDATE contracts
    SET
      proposed_changes = p_changes,
      proposed_by      = auth.uid(),
      status           = 'revision_requested'::public.contract_status,
      updated_at       = now()
