    AS $$
DECLARE
  v_user_id UUID;
BEGIN
  -- 1. Giriş yapmış kullanıcının ID'sini al
  v_user_id := auth.uid();
  
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  -- 2. Kiracı (Tenant) referanslarını temizle
