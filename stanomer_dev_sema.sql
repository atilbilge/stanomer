           FROM public.contracts
          WHERE ((contracts.property_id = p.id) AND (contracts.status = 'active'::public.contract_status))
         LIMIT 1), 'Tenant'::text) AS tenant_name
   FROM ((public.properties p
     LEFT JOIN public.profiles lp ON ((p.landlord_id = lp.id)))
